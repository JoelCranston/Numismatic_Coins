package kotlinx.io

internal fun Short.reverseBytes(): Short {
   return java.lang.Short.reverseBytes(`$this$reverseBytes`);
}

internal fun Int.reverseBytes(): Int {
   return Integer.reverseBytes(`$this$reverseBytes`);
}

internal fun Long.reverseBytes(): Long {
   return java.lang.Long.reverseBytes(`$this$reverseBytes`);
}
